import corpusIndexJson from "./dna/corpus-index.json";

export const CORPUS_INDEX: CorpusEntry[] = corpusIndexJson as CorpusEntry[];

/** 按题材标签/受众在语料库里检索参照剧（用于 prompt 举例与前端展示） */
export function findCorpusRefs(query: { tags?: string[]; audience?: string; limit?: number }): CorpusEntry[] {
  const { tags = [], audience, limit = 5 } = query;
  const scored = CORPUS_INDEX.map((e) => {
    let s = 0;
    for (const t of tags) if (e.tags.some((et) => et.includes(t) || t.includes(et))) s += 2;
    if (audience && e.audience === audience) s += 1;
    if (e.notable && /榜|爆款/.test(e.notable)) s += 1;
    return { e, s };
  })
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s);
  return scored.slice(0, limit).map((x) => x.e);
}
